"""Create a commit-safe, human-readable report from local Praat comparison evidence.

Only hashes, settings, versions and numerical results are exported. Machine-local
paths and raw executable/audio files remain ignored by Git.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def _number(value: object) -> str:
    return f"{value:.6g}" if isinstance(value, float) else str(value)


def render(evidence: dict, comparison: dict) -> str:
    pin = evidence["reference_pin"]
    settings = evidence["settings"]
    by_name = {entry["fixture"]: entry for entry in comparison["fixtures"]}
    lines = [
        "# Observed Praat Gaussian spectrogram reference results",
        "",
        (
            "This report is generated from local reference evidence, "
            "not a substitute for the raw capture."
        ),
        (
            "The original WAV fixtures are deterministic and generated by "
            "`oracle/generate_fixtures.py`."
        ),
        "",
        "## Provenance",
        "",
        f"- Praat version: `{pin['version_reported']}`",
        f"- Installed Praat executable SHA-256: `{pin['sha256']}`",
        f"- Reference OS/CPU: `{evidence['os']}` / `{evidence['cpu']}`",
        f"- Reference capture source commit: `{evidence['source_commit']}`",
        f"- Candidate comparison commit: `{comparison.get('candidate_commit', 'UNAVAILABLE')}`",
        f"- Fixture manifest SHA-256: `{evidence['fixture_manifest_sha256']}`",
        f"- Captured UTC: `{evidence['utc']}`",
        "- Executable provenance: official Praat macOS distribution; exact installer URL/hash",
        "  must be recorded separately if available (the installed binary hash is above).",
        "",
        "## Reference command and settings",
        "",
        (
            "For each fixture the runner executes "
            "`Praat --run oracle/captures/scripts/<fixture>.praat`."
        ),
        "The script reads the generated WAV, runs `To Spectrogram`, then exports a",
        "Praat text Spectrogram. Absolute paths are intentionally omitted from this report.",
        "",
        "```praat",
        'Read from file: "<generated-fixture>.wav"',
        f"To Spectrogram: {settings['window_length_s']}, {settings['maximum_frequency_hz']}, "
        f'{settings["time_step_s"]}, {settings["frequency_step_hz"]}, "{settings["window_shape"]}"',
        'Save as text file: "<capture>.Spectrogram"',
        "```",
        "",
        "`dual_long_30ms` overrides the window length to `0.03` seconds.",
        "All other fixture settings are recorded below and in local `captures/evidence.json`.",
        "",
        "## Fixture-by-fixture results",
        "",
        f"Exploratory comparison thresholds: `atol={comparison['tolerances']['absolute']}`, "(
            f"`rtol={comparison['tolerances']['relative']}`. "
            "These are **not** formally agreed parity thresholds."
        ),
        "",
        (
            "| Fixture | Reference status | Candidate comparison |"
            " Mismatched cells | Max absolute error |"
        ),
        "|---|---|---|---:|---:|",
    ]
    for entry in evidence["runs"]:
        name = entry["fixture"]
        result = by_name.get(name, {"status": "NOT_COMPARED"})
        status = result["status"]
        cells = result.get("mismatched_cells", "—")
        error = (
            _number(result["maximum_absolute_error"]) if "maximum_absolute_error" in result else "—"
        )
        lines.append(f"| `{name}` | `{entry['status']}` | `{status}` | {cells} | {error} |")
    lines += [
        "",
        "## Fixture input/output hashes and overrides",
        "",
        "| Fixture | Input SHA-256 | Reference output SHA-256 | Window (s) |",
        "|---|---|---|---:|",
    ]
    for entry in evidence["runs"]:
        name = entry["fixture"]
        window = entry["settings"]["window_length_s"]
        lines.append(
            f"| `{name}` | `{entry['input_sha256']}` | "
            f"`{entry['output_sha256'] or 'none (expected failure)'}` | {window} |"
        )
    lines += ["", "## Observations and limitations", ""]
    short = by_name.get("short_invalid", {})
    if short.get("status") == "expected_error_match":
        lines.append(
            "- The 8 ms `short_invalid` recording was rejected by both the original Praat"
            " executable and the candidate for insufficient Gaussian window length."
        )
    else:
        lines.append(
            "- Short-signal error parity remains unresolved: "
            + short.get("status", "no result")
            + "."
        )
    stereo = by_name.get("stereo_different", {})
    if stereo.get("status") == "match":
        lines.append(
            "- For the different-channel stereo fixture, Praat matches the candidate's"
            " **combined-channel** power, not either isolated channel."
        )
        for channel, result in stereo.get("individual_channel_checks", {}).items():
            lines.append(
                f"  - {channel}: `{result['status']}`, "
                f"{result.get('mismatched_cells', 'unknown')} mismatched cells; "
                f"max absolute error {_number(result.get('maximum_absolute_error', 'unknown'))}."
            )
    else:
        lines.append(
            "- Stereo combined-channel comparison remains unresolved: "
            + stereo.get("status", "no result")
            + "."
        )
    lines += [
        "- Raw-power comparisons establish numerical agreement only at the stated thresholds;",
        "  they do **not** establish that the label `Pa^2/Hz` is physically correct.",
        "- FFT-bin alignment is covered by axis comparisons; interpretation of the 8x",
        "  frequency-step floor remains a separate documentation question.",
        "- Display/editor/Paint defaults (including 70 dB versus 50 dB dynamic range)",
        "  **have not been captured** by this raw-power oracle and remain pending.",
        "- The runner and candidate exporter do not modify any existing analysis algorithm.",
        "- Local absolute paths, Praat executable, and generated audio are not included.",
        "",
        "## Coordination",
        "",
        "Review with @Comet-Chaser-99 in https://github.com/mhulden/langtools/pull/17",
        "before treating exploratory tolerances as acceptance criteria.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence", type=Path, default=HERE / "captures" / "evidence.json")
    parser.add_argument("--comparison", type=Path, default=HERE / "comparison.json")
    parser.add_argument("--output", type=Path, default=HERE / "docs" / "OBSERVED_RESULTS.md")
    args = parser.parse_args()
    evidence = json.loads(args.evidence.read_text(encoding="utf-8"))
    comparison = json.loads(args.comparison.read_text(encoding="utf-8"))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(evidence, comparison), encoding="utf-8")
    print(f"Report ready: {args.output}")


if __name__ == "__main__":
    main()
